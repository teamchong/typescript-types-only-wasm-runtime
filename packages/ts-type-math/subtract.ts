/**
 * i32 subtract in 8 table lookups instead of one recursion per bit: 2492
 * instantiations per subtract before, ~300 now. Same shape as Add32Nibble in
 * add.ts, including the `extends infer k extends keyof SubNibble` guard - a
 * non-literal key would otherwise index the table as a 512-way union, and
 * eight of those are too complex to represent.
 *
 * Underflow wraps, which is what i32.sub does: the last borrow is discarded.
 */
